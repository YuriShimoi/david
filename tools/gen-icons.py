# Generates ui/Icons.h (ICON_FA_* UTF-8 macros) from Font Awesome's all.min.css.
# Usage: python tools/gen-icons.py <all.min.css> ui/Icons.h
import re, sys

css = open(sys.argv[1], encoding='utf-8').read()
out = ['// Generated by tools/gen-icons.py from Font Awesome Free. Do not edit.', '#pragma once', '']
seen = set()
# Content is a hex escape ("\f068") or an escaped literal character ("\+")
for selectors, code in re.findall(r'([^{}]+)\{--fa:"\\([0-9a-f]+|[^0-9a-f])"', css):
  ch = chr(int(code, 16)) if len(code) > 1 or code.isalnum() else code
  utf8 = ''.join(r'\x%02x' % b for b in ch.encode('utf-8'))
  for name in re.findall(r'\.fa-([a-z0-9-]+)', selectors):
    macro = 'ICON_FA_' + name.upper().replace('-', '_')
    if macro in seen: continue
    seen.add(macro)
    out.append('#define %s "%s"' % (macro, utf8))
out.append('')
open(sys.argv[2], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(seen), 'icons')
